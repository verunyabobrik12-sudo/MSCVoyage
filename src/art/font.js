// Длинное и короткое тире визуально можно рисовать как обычный дефис — так их
// не придётся отдельно кодировать пиксель за пикселем.
const DASH_ALIASES = new Set(['—', '–']);

function getGlyph(ch) {
  if (DASH_ALIASES.has(ch)) return GLYPHS['-'];
  return GLYPHS[ch] || LATIN[ch] || null;
}

/**
 * Рисует пиксельный текст на канвасе.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {{scale?:number, color?:string, spacing?:number, lineHeight?:number}} [opts]
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const scale = opts.scale ?? 1;
  const color = opts.color ?? '#2b1d14';
  const spacing = opts.spacing ?? 1;
  const lineHeight = opts.lineHeight ?? (GLYPH_H + 2);
  const upper = text.toUpperCase();

  ctx.save();
  ctx.fillStyle = color;

  let cursorX = x;
  let cursorY = y;
  for (const ch of upper) {
    if (ch === '\n') {
      cursorX = x;
      cursorY += lineHeight * scale;
      continue;
    }
    const glyph = getGlyph(ch);
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        const line = glyph[row];
        for (let col = 0; col < GLYPH_W; col++) {
          if (line[col] === '#') {
            ctx.fillRect(cursorX + col * scale, cursorY + row * scale, scale, scale);
          }
        }
      }
    }
    cursorX += (GLYPH_W + spacing) * scale;
  }
  ctx.restore();
}

/** Ширина строки текста в пикселях при заданном масштабе (без переносов строк). */
export function measureText(text, scale = 1, spacing = 1) {
  const len = [...text].length;
  return len * (GLYPH_W + spacing) * scale - spacing * scale;
}

export function wrapText(text, maxCharsPerLine) {
  const words = text.split(' ');
  const lines = [];
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length > maxCharsPerLine && current) {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }
  if (current) lines.push(current);
  return lines;
}

